walk_results = []

for i in range(4):

    test_start = train_end + i * block_size

    if i < 3:
        test_end = train_end + (i + 1) * block_size
    else:
        test_end = n

    X_train_wf = X.iloc[:test_start]
    y_train_wf = y.iloc[:test_start]

    X_test_wf = X.iloc[test_start:test_end]
    y_test_wf = y.iloc[test_start:test_end]

    model = ExtraTreesRegressor(
        n_estimators=300,
        random_state=42,
        n_jobs=-1
    )

    model.fit(X_train_wf, y_train_wf)

    pred_wf = model.predict(X_test_wf)

    mae = mean_absolute_error(y_test_wf, pred_wf)
    rmse = np.sqrt(mean_squared_error(y_test_wf, pred_wf))

    smape = np.mean(
        2 * np.abs(y_test_wf.values - pred_wf) /
        (np.abs(y_test_wf.values) + np.abs(pred_wf))
    ) * 100

    walk_results.append({
        "Block": i + 1,
        "Start": data["date"].iloc[test_start],
        "End": data["date"].iloc[test_end - 1],
        "MAE": mae,
        "RMSE": rmse,
        "sMAPE (%)": smape
    })

walk_forward_df = pd.DataFrame(walk_results)

