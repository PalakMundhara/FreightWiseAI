"""### Constructing the Latest Forecasting Features

The latest available dataset is processed using the same feature
engineering logic used during model training.

Lagged values and rolling statistics are constructed using only
information available before the forecast origin, preventing future
information from entering the prediction.
"""

# ---------------------------------------------------------
# 1. Load original cleaned dataset
# ---------------------------------------------------------
df_future = pd.read_csv("/content/master_training_dataset_clean.csv")

df_future["date"] = pd.to_datetime(df_future["date"])
df_future = df_future.sort_values("date").reset_index(drop=True)

# ---------------------------------------------------------
# 2. Basic market features
# ---------------------------------------------------------
df_future["bdry_daily_range"] = (
    df_future["bdry_high"] - df_future["bdry_low"]
)

# ---------------------------------------------------------
# 3. Original BDRY lag features
# ---------------------------------------------------------
df_future["bdry_lag1"] = df_future["bdry_close"].shift(1)
df_future["bdry_lag7"] = df_future["bdry_close"].shift(7)
df_future["bdry_lag30"] = df_future["bdry_close"].shift(30)

# Leakage-safe rolling features:
# only information available BEFORE the current date
df_future["bdry_roll7_mean"] = (
    df_future["bdry_close"]
    .shift(1)
    .rolling(7)
    .mean()
)

df_future["bdry_roll30_mean"] = (
    df_future["bdry_close"]
    .shift(1)
    .rolling(30)
    .mean()
)

# ---------------------------------------------------------
# 4. Additional close lag features
# ---------------------------------------------------------
df_future["close_lag_1"] = df_future["bdry_close"].shift(1)
df_future["close_lag_2"] = df_future["bdry_close"].shift(2)
df_future["close_lag_3"] = df_future["bdry_close"].shift(3)
df_future["close_lag_5"] = df_future["bdry_close"].shift(5)
df_future["close_lag_7"] = df_future["bdry_close"].shift(7)
df_future["close_lag_14"] = df_future["bdry_close"].shift(14)
df_future["close_lag_21"] = df_future["bdry_close"].shift(21)
df_future["close_lag_30"] = df_future["bdry_close"].shift(30)

# ---------------------------------------------------------
# 5. Leakage-safe rolling statistics
# ---------------------------------------------------------
df_future["roll_7_mean"] = (
    df_future["bdry_close"]
    .shift(1)
    .rolling(7)
    .mean()
)

df_future["roll_14_mean"] = (
    df_future["bdry_close"]
    .shift(1)
    .rolling(14)
    .mean()
)

